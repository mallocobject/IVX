// Scripts are C++: keep the identifier rules tight, the name becomes a class
// name and a file name.
bool is_valid_identifier(const std::string &name) {
    if (name.empty()) {
        return false;
    }
    if (!std::isalpha(static_cast<unsigned char>(name[0])) && name[0] != '_') {
        return false;
    }
    for (char c : name) {
        if (!std::isalnum(static_cast<unsigned char>(c)) && c != '_') {
            return false;
        }
    }
    return true;
}

// Templates are raw string literals so they read exactly like the generated
// file: no escaped quotes, no line-ending noise. std::format fills in the
// script name; braces belonging to the C++ code are doubled, which is the only
// escaping left. {0} is the script name (class name and file name are the same
// by convention).
std::string header_template(const std::string &name) {
    return std::format(
        R"(// {0} - generated by VXEdit. Edit freely, then run
// Scripts -> Build & Reload (or the Scripts panel) to hot reload it.
#pragma once

#include "ivx/scene/scriptable_entity.h"

namespace ivx {{

class {0} : public ScriptableEntity {{
  public:
    void on_create() override;
    void on_update(float dt) override;
    void on_destroy() override;
}};

}} // namespace ivx
)",
        name);
}

std::string source_template(const std::string &name) {
    return std::format(
        R"(#include "{0}.h"

#include "ivx/script/script_module.h"
#include "ivx/scene/components.h"

#include <string>

namespace ivx {{

void {0}::on_create() {{
    log("{0} attached to '" + get_component<TagComponent>().tag + "'");
}}

void {0}::on_update(float dt) {{
    (void)dt;
    // auto &transform = get_component<TransformComponent>();
    // transform.rotation += 45.f * dt;
}}

void {0}::on_destroy() {{
}}

// Stays inside namespace ivx: IVX_REGISTER_SCRIPT pastes the type name into an
// identifier, so the type has to be unqualified.
IVX_REGISTER_SCRIPT({0})

}} // namespace ivx
)",
        name);
}

bool write_file(const std::filesystem::path &path, const std::string &content) {
    std::ofstream file{path, std::ios::binary | std::ios::trunc};
    if (!file) {
        return false;
    }
    file << content;
    return file.good();
}

