// Scripts are C++: keep the identifier rules tight, the name becomes a class name
// and a file name.
bool is_valid_identifier(const std::string &name) {
    if (name.empty()) {
        return false;
    }
    if (!std::isalpha(static_cast<unsigned char>(name[0])) && name[0] != '_') {
        return false;
    }
    for (char c : name) {
        if (!std::isalnum(static_cast<unsigned char>(c)) && c != '_') {
            return false;
        }
    }
    return true;
}

std::string header_template(const std::string &name) {
    return "// " + name + " - generated by VXEdit. Edit freely, then run\n"
           "// Scripts -> Build & Reload (or the Scripts panel) to hot reload it.\n"
           "#pragma once\n"
           "\n"
           "#include \"ivx/scene/scriptable_entity.h\"\n"
           "\n"
           "namespace ivx {\n"
           "\n"
           "class " +
           name +
           " : public ScriptableEntity {\n"
           "  public:\n"
           "    void on_create() override;\n"
           "    void on_update(float dt) override;\n"
           "    void on_destroy() override;\n"
           "};\n"
           "\n"
           "} // namespace ivx\n";
}

std::string source_template(const std::string &name) {
    return "#include \"" + name + ".h\"\n"
           "\n"
           "#include \"ivx/script/script_module.h\"\n"
           "#include \"ivx/scene/components.h\"\n"
           "\n"
           "#include <string>\n"
           "\n"
           "namespace ivx {\n"
           "\n"
           "void " +
           name +
           "::on_create() {\n"
           "    log(\"" + name + " attached to '\" +\n"
           "        get_component<TagComponent>().tag + \"'\");\n"
           "}\n"
           "\n"
           "void " +
           name +
           "::on_update(float dt) {\n"
           "    (void)dt;\n"
           "    // auto &transform = get_component<TransformComponent>();\n"
           "    // transform.rotation += 45.f * dt;\n"
           "}\n"
           "\n"
           "void " +
           name +
           "::on_destroy() {\n"
           "}\n"
           "\n"
           "// Stays inside namespace ivx: IVX_REGISTER_SCRIPT pastes the type name\n"
           "// into an identifier, so the type has to be unqualified.\n"
           "IVX_REGISTER_SCRIPT(" +
           name + ")\n"
           "\n"
           "} // namespace ivx\n";
}

bool write_file(const std::filesystem::path &path, const std::string &content) {
    std::ofstream file{path, std::ios::binary | std::ios::trunc};
    if (!file) {
        return false;
    }
    file << content;
    return file.good();
}

