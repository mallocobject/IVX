ScriptHost::ScriptHost() : scripts_dir_{SCRIPTS_DIR} {
}

ScriptHost::~ScriptHost() {
    // Never leave a build running across destruction: it captures `this`.
    if (worker_.joinable()) {
        worker_.join();
    }

    // Belt and braces: the instances live in the module, so they have to be
    // gone before `library_` drops it. The editor already does this in
    // on_detach().
    unbind_all();
}

void ScriptHost::release_all_scripts() {
    unbind_all();
}

std::size_t ScriptHost::bind_scene_scripts() {
    if (scene_ == nullptr || !library_.is_loaded()) {
        return 0;
    }

    std::size_t bound = 0;
    for (auto [handle, script] :
         scene_->registry().view<NativeScriptComponent>().each()) {
        // Already live, or a component the user added but never bound: nothing
        // to do.
        if (script.script_name.empty() || script.instantiate != nullptr) {
            continue;
        }
        if (ScriptRegistry::get().bind_by_name(script.script_name,
                                               Entity{handle, scene_})) {
            ++bound;
        } else {
            IVX_WARN("Scripts: '{}' is not a known script type",
                     script.script_name);
        }
    }

    if (bound > 0) {
        IVX_INFO("Scripts: bound {} script(s) from the loaded scene", bound);
    }
    return bound;
}

bool ScriptHost::load_initial(std::string &error) {
    const bool loaded = library_.load(SCRIPTS_DLL, error);
    if (!loaded) {
        // The module on disk is unusable. Whatever put it there (a stale build,
        // a file copied from another configuration), a plain rebuild would
        // answer "no work to do" because the DLL looks newer than its sources.
        // begin_build() deletes the file first, which forces a relink.
        force_rebuild_ = true;
    }
    return loaded;
}

namespace {
// Folds the newest matching file under `directory` into `latest`. A missing
// directory is not an error here: the iterator is simply empty.
void fold_since_module(const std::filesystem::path &directory,
                       std::initializer_list<std::string_view> extensions,
                       bool recursive,
                       std::filesystem::file_time_type &latest) {
    std::error_code dir_ec;
    if (recursive) {
        fold_newest(
            std::filesystem::recursive_directory_iterator{directory, dir_ec},
            extensions,
            latest);
    } else {
        fold_newest(std::filesystem::directory_iterator{directory, dir_ec},
                    extensions,
                    latest);
    }
}
} // namespace

bool ScriptHost::has_newer_sources() const {
    std::error_code ec;
    const std::filesystem::path module{SCRIPTS_DLL};
    const auto module_time = std::filesystem::last_write_time(module, ec);
    if (ec) {
        return false; // no module yet: the caller builds it regardless
    }

    std::filesystem::file_time_type latest = module_time;

    // The script project is flat (sources, headers and its CMakeLists next to
    // each other), so a plain directory_iterator is enough.
    fold_since_module(scripts_dir_, {".cpp", ".h", ".hpp"}, false, latest);
    // The file list is a glob, so touching CMakeLists also needs a rebuild.
    const std::filesystem::path cmake_lists =
        scripts_dir_ / std::filesystem::path{"CMakeLists.txt"};
    std::error_code file_ec;
    const auto cmake_time =
        std::filesystem::last_write_time(cmake_lists, file_ec);
    if (!file_ec && cmake_time > latest) {
        latest = cmake_time;
    }

    return latest > module_time;
}

std::filesystem::file_time_type ScriptHost::newest_engine_header() const {
    // A file_time_type default value means "nothing found": the loop below
    // starts from the epoch, so any real file wins.
    std::filesystem::file_time_type latest{};
    fold_since_module(std::filesystem::path{IVX_ROOT_DIR} / "IVX" / "src",
                      {".h", ".hpp"},
                      true,
                      latest);
    return latest;
}

bool ScriptHost::has_newer_engine_headers() const {
    std::error_code ec;
    const auto module_time = std::filesystem::last_write_time(
        std::filesystem::path{SCRIPTS_DLL}, ec);
    if (ec) {
        return false; // no module yet: load_initial() already schedules the
                      // first build
    }

    // `fold_since_module` only raises `latest`, so seeding it with the module
    // timestamp turns the answer into "is any header newer than the module".
    std::filesystem::file_time_type latest = module_time;
    fold_since_module(std::filesystem::path{IVX_ROOT_DIR} / "IVX" / "src",
                      {".h", ".hpp"},
                      true,
                      latest);
    return latest > module_time;
}

void ScriptHost::unbind_all() {
    if (scene_ == nullptr) {
        return;
    }
    for (auto [handle, script] :
         scene_->registry().view<NativeScriptComponent>().each()) {
        script.unbind();
    }
}

bool ScriptHost::needs_reconfigure() const {
    // The script module has its own standalone Ninja project
    // (SCRIPTS_PROJECT_DIR) and its own build directory. Configuring is a
    // one-time cost: after that Ninja re-runs CMake by itself when scripts are
    // added or removed, thanks to CONFIGURE_DEPENDS in that project.
    //
    // A tree that remembers another configuration or another checkout root is
    // not usable either: its include paths point somewhere else, so the build
    // dies on the first #include. script_project_needs_reconfigure() covers
    // those cases and the configure pass wipes the tree.
    return script_project_needs_reconfigure();
}

bool ScriptHost::begin_build(bool clean) {
    if (building_) {
        return false;
    }
    if (clean) {
        force_rebuild_ = true;
    }

    // Remember the bindings before the instances (and their script_name) go
    // away, so they can be restored against the new module.
    pending_bindings_.clear();
    if (scene_ != nullptr) {
        for (auto [handle, script] :
             scene_->registry().view<NativeScriptComponent>().each()) {
            if (!script.script_name.empty()) {
                pending_bindings_.push_back(
                    {static_cast<std::uint32_t>(handle), script.script_name});
            }
        }
    }

    // Unbind and unload now: instances live in the module, and the linker
    // cannot overwrite a DLL that is still mapped into the process.
    unbind_all();
    library_.unload();

    // A module that was rejected (stale layout, copied in from another
    // configuration) is newer than its own sources, so Ninja would answer "no
    // work to do" and the module would stay rejected forever. Deleting the DLL
    // alone is not enough: the *objects* can be stale as well (a header change
    // Ninja's dependency database missed), and re-linking them reproduces the
    // same rejected module - which is how a rejected module could never
    // recover. `--clean-first` discards the objects without touching the rules;
    // it costs a few seconds and only happens after a rejection.
    const bool clean_first = force_rebuild_;
    if (clean_first) {
        std::error_code ignored;
        std::filesystem::remove(SCRIPTS_DLL, ignored);
        force_rebuild_ = false;
    }

    // Only a changed file *set* needs a configure pass (the sources are
    // globbed); a plain source edit goes straight to the compiler.
    last_build_reconfigured_ = needs_reconfigure();

    building_ = true;
    build_seconds_ = 0.f;
    build_start_ = std::chrono::steady_clock::now();
    last_log_.clear();

    const bool reconfigure = last_build_reconfigured_;
    IVX_INFO("Scripts: building{}{}",
             reconfigure ? " (reconfiguring, file set changed)" : "",
             clean_first
                 ? " (clean rebuild: headers changed or module rejected)"
                 : "");

    // The worker only compiles. Everything that touches the scene or the loader
    // stays on the main thread (see poll_build()).
    worker_ = std::thread{[this, reconfigure, clean_first] {
        std::string log;
        const bool ok = build_script_module(reconfigure, clean_first, log);
        // The thread's last statement: publish the result.
        {
            std::lock_guard<std::mutex> lock(result_mutex_);
            worker_log_ = std::move(log);
            worker_ok_ = ok;
        }
        worker_done_ = true;
    }};
    return true;
}

void ScriptHost::poll_build() {
    if (!building_) {
        return;
    }

    build_seconds_ = std::chrono::duration<float>(
                         std::chrono::steady_clock::now() - build_start_)
                         .count();

    if (!worker_done_) {
        return; // still compiling
    }

    worker_.join();

    {
        std::lock_guard<std::mutex> lock(result_mutex_);
        last_log_ = std::move(worker_log_);
        worker_log_.clear();
        last_build_ok_ = worker_ok_;
    }
    worker_done_ = false;

    // Load even when the build failed: the linker did not touch the old DLL in
    // that case, so the previous code keeps working instead of leaving the
    // editor without any script types.
    std::string error;
    const bool loaded = library_.load(SCRIPTS_DLL, error);
    if (!loaded) {
        last_log_ += "\n" + error;
    }

    std::size_t restored = 0;
    if (scene_ != nullptr) {
        for (const PendingBinding &binding : pending_bindings_) {
            const entt::entity handle =
                static_cast<entt::entity>(binding.handle);
            if (!scene_->registry().valid(handle)) {
                continue;
            }
            if (ScriptRegistry::get().bind_by_name(binding.name,
                                                   Entity{handle, scene_})) {
                restored++;
            }
        }
    }
    pending_bindings_.clear();

    building_ = false;
    build_seconds_ = std::chrono::duration<float>(
                         std::chrono::steady_clock::now() - build_start_)
                         .count();

    if (!loaded) {
        // The compiler was happy but the module is unusable (stale layout,
        // missing export, wrong architecture). Say so: "build failed" would
        // send the reader to the compiler output, which is empty in this case.
        IVX_ERROR("Scripts: build {}, but the module was rejected: {}",
                  last_build_ok_ ? "ok" : "failed",
                  error);
        // Force the next attempt to relink instead of trusting the timestamp: a
        // DLL that was copied in from another configuration looks newer than
        // its sources, so Ninja would answer "no work to do" and the module
        // would stay rejected forever.
        force_rebuild_ = true;
        return;
    }

    IVX_INFO(
        "Scripts: build {}{} in {:.2f} s, {} type(s), {} binding(s) restored",
        last_build_ok_ ? "ok" : "FAILED",
        last_build_reconfigured_ ? " (reconfigured)" : "",
        build_seconds_,
        ScriptRegistry::get().entries().size(),
        restored);
    if (!last_build_ok_) {
        // Loading the previous DLL still works when the build failed, so the
        // editor keeps its script types; the compiler output is in the Build
        // tab.
        IVX_ERROR(
            "Script build failed — the compiler output is in the Build tab");
    }
}

bool ScriptHost::create_script(const std::string &name,
                               std::filesystem::path &header_path,
                               std::filesystem::path &source_path,
                               std::string &error) {
    if (!is_valid_identifier(name)) {
        error = "Script name must be a valid C++ identifier";
        return false;
    }

    header_path = scripts_dir_ / (name + ".h");
    source_path = scripts_dir_ / (name + ".cpp");
    if (std::filesystem::exists(header_path) ||
        std::filesystem::exists(source_path)) {
        error = name + " already exists in scripts/";
        return false;
    }

    if (!write_file(header_path, header_template(name))) {
        error = "could not write " + header_path.string();
        return false;
    }
    if (!write_file(source_path, source_template(name))) {
        error = "could not write " + source_path.string();
        return false;
    }

    IVX_INFO("Created script '{}' ({})", name, source_path.string());
    return true;
}

std::filesystem::path ScriptHost::script_path(const std::string &name) const {
    return scripts_dir_ / (name + ".cpp");
}

