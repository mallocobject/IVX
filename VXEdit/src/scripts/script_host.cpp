ScriptHost::ScriptHost() : scripts_dir_{SCRIPTS_DIR} {
}

bool ScriptHost::load_initial(std::string &error) {
    return library_.load(SCRIPTS_DLL, error);
}

void ScriptHost::unbind_all() {
    if (scene_ == nullptr) {
        return;
    }
    for (auto [handle, script] :
         scene_->registry().view<NativeScriptComponent>().each()) {
        script.unbind(); // clears script_name too; captured below
    }
}

bool ScriptHost::scripts_dir_changed() {
    std::vector<std::string> current;
    std::error_code error;
    for (const auto &entry :
         std::filesystem::directory_iterator{scripts_dir_, error}) {
        if (!entry.is_regular_file()) {
            continue;
        }
        const std::string extension = entry.path().extension().string();
        if (extension == ".h" || extension == ".cpp") {
            current.push_back(entry.path().filename().string());
        }
    }
    if (error) {
        return false;
    }
    std::sort(current.begin(), current.end());
    if (current == known_sources_) {
        return false;
    }
    known_sources_ = std::move(current);
    return true;
}

bool ScriptHost::build_and_reload(std::string &log) {
    // Remember the bindings before the instances (and their script_name) go
    // away, so they can be restored against the new module.
    std::vector<std::pair<Entity, std::string>> bindings;
    if (scene_ != nullptr) {
        for (auto [handle, script] :
             scene_->registry().view<NativeScriptComponent>().each()) {
            if (!script.script_name.empty()) {
                bindings.emplace_back(Entity{handle, scene_}, script.script_name);
            }
        }
    }

    // Unbind first: instances live in the module and the linker cannot overwrite
    // a DLL that is still mapped into the process.
    unbind_all();
    library_.unload();

    // A changed file *set* needs a re-configure (the sources are globbed); a plain
    // source edit goes straight to the compiler.
    last_build_reconfigured_ = scripts_dir_changed() || !has_built_once_;
    has_built_once_ = true;

    const auto start = std::chrono::steady_clock::now();
    const bool ok = rebuild_scripts(library_, last_build_reconfigured_, log);
    last_build_ms_ = std::chrono::duration<float, std::milli>(
                         std::chrono::steady_clock::now() - start)
                         .count() /
                     1000.f;

    std::size_t restored = 0;
    if (scene_ != nullptr) {
        for (auto &[entity, name] : bindings) {
            if (ScriptRegistry::get().bind_by_name(name, entity)) {
                restored++;
            }
        }
    }

    IVX_INFO("Scripts: {} type(s), {} binding(s) restored{}",
             ScriptRegistry::get().entries().size(),
             restored,
             ok ? "" : " (build failed)");
    return ok;
}

bool ScriptHost::create_script(const std::string &name,
                               std::filesystem::path &header_path,
                               std::filesystem::path &source_path,
                               std::string &error) {
    if (!is_valid_identifier(name)) {
        error = "Script name must be a valid C++ identifier";
        return false;
    }

    header_path = scripts_dir_ / (name + ".h");
    source_path = scripts_dir_ / (name + ".cpp");
    if (std::filesystem::exists(header_path) ||
        std::filesystem::exists(source_path)) {
        error = name + " already exists in scripts/";
        return false;
    }

    if (!write_file(header_path, header_template(name))) {
        error = "could not write " + header_path.string();
        return false;
    }
    if (!write_file(source_path, source_template(name))) {
        error = "could not write " + source_path.string();
        return false;
    }

    IVX_INFO("Created script '{}' ({})", name, source_path.string());
    return true;
}

std::filesystem::path ScriptHost::script_path(const std::string &name) const {
    return scripts_dir_ / (name + ".cpp");
}

